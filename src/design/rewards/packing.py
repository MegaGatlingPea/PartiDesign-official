@dataclass(frozen=True, slots=True)
class _VendorRuntime:
    parse_pdb: Any
    featurize: Any
    pack_side_chains: Any
    packer_type: Any
    device: torch.device
    denoising_steps: int
    samples: int


@dataclass(frozen=True, slots=True)
class _CandidatePlan:
    candidate: SearchCandidate
    sequence_plan: SequenceSourcePlan
    target_by_residue_uid: Mapping[int, str]
    mutable_residue_uids: frozenset[int]
    protected_residue_uids: frozenset[int]
    design_chain_ids: frozenset[str] | None = None


def _mapping(value: Any) -> Mapping[str, Any]:
    return value if isinstance(value, Mapping) else {}


def _packing_options(reward_config: Mapping[str, Any]) -> Mapping[str, Any]:
    sequence = _mapping(reward_config.get("sequence", reward_config))
    explicit = sequence.get("packing")
    if isinstance(explicit, Mapping):
        return explicit
    # Keep the established sequence subtree as the only user-facing source of
    # device/step overrides while using the mandatory side-chain checkpoint.
    ligand = _mapping(sequence.get("ligandmpnn"))
    return ligand


def validate_packing_assets(repo_root: Path) -> None:
    """Check the vendored side-chain source and mandatory checkpoint only."""

    root = Path(repo_root)
    source = community_source("ligandmpnn", root)
    checkpoint = (
        community_asset("ligandmpnn", root) / "checkpoint"
        / "ligandmpnn_sc_v_32_002_16.pt"
    )
    missing = [str(path) for path in (source, checkpoint) if not path.exists()]
    if not source.is_dir():
        missing.append(f"{source}/<directory>")
    for name in ("data_utils.py", "sc_utils.py", "model_utils.py"):
        path = source / name
        if not path.is_file():
            missing.append(str(path))
    if missing:
        raise PackingSystemError("LigandMPNN packing assets are missing: " + ", ".join(missing))


def _module_is_from(module: Any, source: Path) -> bool:
    path = getattr(module, "__file__", None)
    if not path:
        return False
    try:
        Path(path).resolve().relative_to(source.resolve())
    except ValueError:
        return False
    return True


def _packing_device(repo_root: Path, requested_device: str) -> torch.device:
    """Map the existing MPNN physical owner back into this process's namespace."""
    if requested_device not in {"cuda", "cuda:0"}:
        return torch.device(requested_device)
    import os
    from .mpnn import MPNNSystemError, _offline_environment

    try:
        physical_owner = _offline_environment(repo_root)["CUDA_VISIBLE_DEVICES"]
    except MPNNSystemError as exc:
        raise PackingSystemError(str(exc)) from exc
    visible = os.environ.get("CUDA_VISIBLE_DEVICES")
    logical_index = (
        int(physical_owner) if visible is None
        else [value.strip() for value in visible.split(",")].index(physical_owner)
    )
    return torch.device(f"cuda:{logical_index}")


def _load_vendor_runtime(repo_root: Path, reward_config: Mapping[str, Any]) -> _VendorRuntime:
    validate_packing_assets(repo_root)
    source = (community_source("ligandmpnn", Path(repo_root))).resolve()
    previous_path = list(sys.path)
    source_text = str(source)
    saved_modules = {
        name: module
        for name, module in list(sys.modules.items())
        if name == "data_utils"
        or name == "sc_utils"
        or name == "model_utils"
        or name == "openfold"
        or name.startswith("openfold.")
    }
    for name in list(sys.modules):
        if (
            name == "data_utils"
            or name == "sc_utils"
            or name == "model_utils"
            or name == "openfold"
            or name.startswith("openfold.")
        ):
            del sys.modules[name]
    if source_text not in sys.path:
        sys.path.insert(0, source_text)
    try:
        data_utils = importlib.import_module("data_utils")
        sc_utils = importlib.import_module("sc_utils")
    except Exception as exc:  # dependency/import failure is owner-systemic
        raise PackingSystemError(f"cannot import LigandMPNN packing runtime: {exc}") from exc
    finally:
        # The modules retain their loaded bare dependencies; do not let this
        # vendor path silently shadow the rest of the application afterward.
        sys.path[:] = previous_path
        for name in list(sys.modules):
            if (
                name == "data_utils"
                or name == "sc_utils"
                or name == "model_utils"
                or name == "openfold"
                or name.startswith("openfold.")
            ):
                del sys.modules[name]
        sys.modules.update(saved_modules)
    if not (_module_is_from(data_utils, source) and _module_is_from(sc_utils, source)):
        raise PackingSystemError("LigandMPNN vendor module name is already owned by another checkout")

    options = _packing_options(reward_config)
    requested_device = str(options.get("device", "cuda" if torch.cuda.is_available() else "cpu"))
    if requested_device.startswith("cuda") and not torch.cuda.is_available():
        raise PackingSystemError(f"packing device {requested_device!r} is unavailable")
    device = _packing_device(repo_root, requested_device)
    checkpoint = community_asset("ligandmpnn", Path(repo_root)) / "checkpoint" / "ligandmpnn_sc_v_32_002_16.pt"
    try:
        payload = torch.load(checkpoint, map_location=device, weights_only=False)
        model = sc_utils.Packer(
            node_features=128,
            edge_features=128,
            num_positional_embeddings=16,
            num_chain_embeddings=16,
            num_rbf=16,
            hidden_dim=128,
            num_encoder_layers=3,
            num_decoder_layers=3,
            atom_context_num=16,
            lower_bound=0.0,
            upper_bound=20.0,
            top_k=32,
            dropout=0.0,
            augment_eps=0.0,
            atom37_order=False,
            device=device,
            num_mix=3,
        )
        state = payload["model_state_dict"]
        model.load_state_dict(state)
        model.to(device)
        model.eval()
    except Exception as exc:
        raise PackingSystemError(f"cannot load LigandMPNN side-chain checkpoint: {exc}") from exc

    denoising_steps = int(options.get("sc_num_denoising_steps", options.get("denoising_steps", 3)))
    samples = int(options.get("sc_num_samples", options.get("samples", 16)))
    if denoising_steps < 1 or samples < 1:
        raise PackingSystemError("packing denoising_steps and samples must be positive")
    if bool(options.get("repack_everything", False)):
        raise PackingSystemError("packing must keep fixed side chains; repack_everything is unsupported")
    return _VendorRuntime(
        parse_pdb=data_utils.parse_PDB,
        featurize=data_utils.featurize,
        pack_side_chains=sc_utils.pack_side_chains,
        packer_type=model,
        device=device,
        denoising_steps=denoising_steps,
        samples=samples,
    )


def _atom_row_by_uid(atoms: Any) -> dict[int, int]:
    return {int(value): index for index, value in enumerate(np.asarray(atoms.atom_uid, dtype=np.int64))}


def _residue_rows(atoms: Any) -> dict[int, np.ndarray]:
    result: dict[int, np.ndarray] = {}
    for uid in dict.fromkeys(int(value) for value in np.asarray(atoms.residue_uid, dtype=np.int64)):
        result[uid] = np.flatnonzero(np.asarray(atoms.residue_uid, dtype=np.int64) == uid)
    return result


def _one_letter_for_source(candidate: SearchCandidate, residue_uid: int, source_name: str) -> str | None:
    source_name = source_name.upper()
    if source_name in _AA3_TO_AA1:
        return _AA3_TO_AA1[source_name]
    parent = candidate.model_parent_residue.get(residue_uid)
    if parent is None:
        parent = candidate.fixed_modified_parent_residue.get(residue_uid)
    if parent is None:
        return None
    return _AA3_TO_AA1.get(str(parent).upper())


def _protected_residues(
    candidate: SearchCandidate, *, release_backbone_motifs: bool = True
) -> set[int]:
    atoms = candidate.atoms
    rows_by_uid = _residue_rows(atoms)
    protected: set[int] = set()
    if "motif_coord_condition" in atoms.get_annotation_categories():
        for uid, rows in rows_by_uid.items():
            motif = np.asarray(atoms.motif_coord_condition[rows], dtype=bool)
            if not bool(motif.any()):
                continue
            # A copied unknown motif contributes a coordinate-conditioned
            # backbone frame while leaving its identity to the sequence model.
            # Such a residue is still safe to repack: reconstruction retains the
            # source backbone rows and only replaces its side-chain inventory.
            # Every other motif (known identity, non-design context, or a
            # selected side-chain atom) remains protected from mutation.
            design_owned = bool(np.asarray(atoms.is_design[rows], dtype=bool).all())
            identity_fixed = bool(
                np.asarray(atoms.identity_condition[rows], dtype=bool).any()
            )
            motif_names = np.asarray(atoms.atom_name[rows]).astype(str)[motif]
            backbone_only = bool(np.isin(motif_names, tuple(_BACKBONE)).all())
            release_allowed = (
                release_backbone_motifs
                and design_owned
                and not identity_fixed
                and backbone_only
            )
            if not release_allowed:
                protected.add(uid)

    atom_row = _atom_row_by_uid(atoms)
    for condition in candidate.topology_conditions:
        for raw_uid in (condition.atom_uid_a, condition.atom_uid_b):
            row = atom_row.get(int(raw_uid))
            if row is None:
                raise PackingCandidateError(
                    f"topology condition references missing atom UID {raw_uid}"
                )
            if str(atoms.atom_name[row]) not in _BACKBONE:
                protected.add(int(atoms.residue_uid[row]))

    if atoms.bonds is not None:
        for raw_i, raw_j, _order in atoms.bonds.as_array():
            i, j = int(raw_i), int(raw_j)
            if int(atoms.residue_uid[i]) == int(atoms.residue_uid[j]):
                continue
            if str(atoms.atom_name[i]) not in _BACKBONE:
                protected.add(int(atoms.residue_uid[i]))
            if str(atoms.atom_name[j]) not in _BACKBONE:
                protected.add(int(atoms.residue_uid[j]))
    return protected


def _candidate_plan(
    candidate: SearchCandidate,
    plan: SequenceSourcePlan,
    *,
    mutable_residue_uids: frozenset[int] | None = None,
    design_chain_ids: frozenset[str] | None = None,
) -> _CandidatePlan:
    if plan.design_chain is None and design_chain_ids is None:
        raise PackingCandidateError("MPNN plan has no design chain")
    tokens = protein_tokens(candidate.atoms)
    selected_chains = (
        frozenset(str(value) for value in design_chain_ids)
        if design_chain_ids is not None
        else frozenset({str(plan.design_chain)})
    )
    if not any(str(token.chain_id) in selected_chains for token in tokens):
        raise PackingCandidateError(
            f"MPNN design chain {plan.design_chain!r} has no protein tokens"
        )
    if mutable_residue_uids is None:
        has_design = any(
            bool(token.is_design) and str(token.chain_id) in selected_chains
            for token in tokens
        )
    else:
        has_design = any(
            int(token.residue_uid) in mutable_residue_uids
            and str(token.chain_id) in selected_chains
            for token in tokens
        )
    if not has_design:
        raise PackingCandidateError(
            f"MPNN design chain {plan.design_chain!r} has no design residues"
        )
    protected = _protected_residues(
        candidate, release_backbone_motifs=mutable_residue_uids is None
    )
    rows_by_uid = _residue_rows(candidate.atoms)
    target_by_uid: dict[int, str] = {}
    mutable: set[int] = set()
    explicit_mutable = (
        None
        if mutable_residue_uids is None
        else frozenset(int(value) for value in mutable_residue_uids)
    )
    seen_uids: set[int] = set()
    fixed_positions = {(str(chain), int(position)) for chain, position in plan.fixed_positions}
    fixed_modified_names = {
        int(residue_uid): str(component_id).upper()
        for residue_uid, component_id in candidate.fixed_modified_residue_names.items()
    }
    fixed_modified_parents = {
        int(residue_uid): str(parent).upper()
        for residue_uid, parent in candidate.fixed_modified_parent_residue.items()
    }

    for token in tokens:
        uid = int(token.residue_uid)
        source_name = str(token.residue_name).upper()
        sequence = str(plan.chain_sequences.get(token.chain_id, ""))
        if token.position < 1 or token.position > len(sequence):
            raise PackingCandidateError(
                f"plan sequence is missing {token.chain_id}:{token.position}"
            )
        target_name = _AA1_TO_AA3.get(sequence[token.position - 1].upper())
        if target_name is None:
            raise PackingCandidateError(
                f"plan sequence has unsupported residue {sequence[token.position - 1]!r} "
                f"at {token.chain_id}:{token.position}"
            )
        source_one = _one_letter_for_source(candidate, uid, source_name)
        is_design = bool(token.is_design)
        if explicit_mutable is not None:
            is_design = uid in explicit_mutable
            seen_uids.add(uid)
        is_fixed_modified = uid in fixed_modified_names
        if is_fixed_modified:
            if source_name != fixed_modified_names[uid]:
                raise PackingCandidateError(
                    f"fixed modified residue UID {uid} disagrees with candidate source "
                    f"identity {source_name!r} versus {fixed_modified_names[uid]!r}"
                )
            parent = fixed_modified_parents.get(uid)
            if parent not in _AA3_TO_AA1:
                raise PackingCandidateError(
                    f"fixed modified residue {source_name!r} lacks a canonical protein parent"
                )
            # A fixed modified occurrence is represented by its canonical parent
            # in the private sequence, but its source inventory is never sent
            # through the standard atom14 reconstruction path.
            if source_one != sequence[token.position - 1].upper():
                raise PackingCandidateError(
                    f"fixed residue identity changes at {token.chain_id}:{token.position}"
                )
        if is_design and str(token.chain_id) not in selected_chains:
            raise PackingCandidateError(
                f"design residue {token.chain_id}:{token.position} is outside plan design chains"
            )
        target_by_uid[uid] = target_name
        if (token.chain_id, token.position) in fixed_positions:
            if source_one is not None and source_one != sequence[token.position - 1].upper():
                raise PackingCandidateError(
                    f"fixed residue identity changes at {token.chain_id}:{token.position}"
                )
        if is_design and source_name not in _AA3_TO_AA1 and not is_fixed_modified:
            # Unsupported modified design residues are safe only when the
            # authoritative fixed-modified ledger identifies them.
            raise PackingCandidateError(
                f"modified residue {source_name} at {token.chain_id}:{token.position} cannot be packed"
            )
        # Sequence-fixed means identity-fixed only.  Motif coordinates,
        # explicit side-chain endpoints and non-design context are the
        # conservative coordinate protections.
        if explicit_mutable is not None and uid in explicit_mutable and (
            uid in protected or is_fixed_modified
        ):
            raise PackingCandidateError(
                f"antibody mutable residue UID {uid} is protected by topology or "
                "fixed-modified identity"
            )
        if (
            explicit_mutable is not None
            and uid not in explicit_mutable
            and source_one is not None
            and source_one != sequence[token.position - 1].upper()
        ):
            raise PackingCandidateError(
                f"antibody protected residue UID {uid} changed identity"
            )
        must_preserve = uid in protected or is_fixed_modified
        if not is_design:
            must_preserve = True
        if must_preserve:
            if source_one is not None and source_one != sequence[token.position - 1].upper():
                raise PackingCandidateError(
                    f"fixed residue identity changes at {token.chain_id}:{token.position}"
                )
            continue
        if source_name not in _AA3_TO_AA1:
            raise PackingCandidateError(
                f"non-standard design residue {source_name} has no packer atom inventory"
            )
        mutable.add(uid)

    if explicit_mutable is not None:
        missing = explicit_mutable - seen_uids
        if missing:
            raise PackingCandidateError(
                "antibody mutable residue UIDs are absent from protein token ledger: "
                + ", ".join(str(value) for value in sorted(missing))
            )

    # Ensure topology endpoints on a mutable residue are retained under a
    # stable atom name.  The protected pass above handles all side-chain edges.
    for uid in mutable:
        if uid not in rows_by_uid:
            raise PackingCandidateError(f"design residue UID {uid} is absent")
    return _CandidatePlan(
        candidate=candidate,
        sequence_plan=plan,
        target_by_residue_uid=target_by_uid,
        mutable_residue_uids=frozenset(mutable),
        protected_residue_uids=frozenset(protected),
        design_chain_ids=(
            selected_chains if design_chain_ids is not None else None
        ),
    )


def _bond_rows_array(bonds: Any) -> np.ndarray:
    if bonds is None:
        return np.empty((0, 3), dtype=np.uint32)
    return np.asarray(bonds.as_array(), dtype=np.uint32).reshape((-1, 3))


def _pack_input_bonds(candidate_plan: _CandidatePlan, atoms: Any) -> Any:
    candidate = candidate_plan.candidate
    rows_by_uid = _residue_rows(atoms)
    entries: dict[tuple[int, int], int] = {}
    for uid in candidate_plan.mutable_residue_uids:
        rows = rows_by_uid[uid]
        local = struc.connect_via_residue_names(atoms[rows], inter_residue=False).as_array()
        for i, j, order in local:
            left, right = int(rows[int(i)]), int(rows[int(j)])
            entries[(min(left, right), max(left, right))] = int(order)
    uid_by_row = np.asarray(atoms.residue_uid, dtype=np.int64)
    atom_names = np.asarray(atoms.atom_name).astype(str)
    for raw_i, raw_j, raw_order in _bond_rows_array(candidate.atoms.bonds):
        i, j = int(raw_i), int(raw_j)
        if i >= len(candidate.atoms) or j >= len(candidate.atoms):
            continue
        uid_i, uid_j = int(uid_by_row[i]), int(uid_by_row[j])
        if uid_i == uid_j and uid_i in candidate_plan.mutable_residue_uids:
            continue
        if uid_i in candidate_plan.mutable_residue_uids and atom_names[i] not in _BACKBONE:
            continue
        if uid_j in candidate_plan.mutable_residue_uids and atom_names[j] not in _BACKBONE:
            continue
        key = (min(i, j), max(i, j))
        entries[key] = int(raw_order)
    data = np.asarray(
        [[i, j, order] for (i, j), order in sorted(entries.items())], dtype=np.uint32
    )
    return struc.BondList(len(atoms), data.reshape((-1, 3)))


def _safe_work_name(candidate_id: str) -> str:
    name = re.sub(r"[^A-Za-z0-9_.-]+", "_", str(candidate_id)).strip("._")
    return name[:80] or "candidate"


def _prepare_candidate(
    candidate_plan: _CandidatePlan,
    *,
    repo_root: Path,
    work_dir: Path,
    pipetools_api: Any,
    model_types: tuple[Any, Any, Any],
) -> tuple[_CandidatePlan, Any, dict[int, int]]:
    """Prepare an owner-local PDB and map vendor residue indices to ResidueUID."""

    candidate = candidate_plan.candidate
    atoms = candidate.atoms.copy()
    rows_by_uid = _residue_rows(atoms)
    for uid in candidate_plan.mutable_residue_uids:
        rows = rows_by_uid[uid]
        atoms.res_name[rows] = candidate_plan.target_by_residue_uid[uid]
    atoms.bonds = _pack_input_bonds(candidate_plan, atoms)
    from .mpnn import MPNNSequenceError, _canonical_sample
    from pipetools.errors import ConfigError, StructureError

    try:
        packed_candidate = replace(candidate, atoms=atoms)
        canonical_sample = _canonical_sample(
            packed_candidate,
            candidate_plan.sequence_plan,
            work_dir,
            model_types,
            design_chain_ids=candidate_plan.design_chain_ids,
        )
        prepared = pipetools_api[0](canonical_sample, work_dir, ca_only=False, materialize=True)
    except PackingSystemError:
        raise
    except (MPNNSequenceError, ConfigError, StructureError, ValueError) as exc:
        raise PackingCandidateError(f"cannot prepare packing input: {exc}") from exc

    return candidate_plan, prepared, {}


def _feature_dict(
    candidate_plan: _CandidatePlan,
    prepared: Any,
    vendor: _VendorRuntime,
) -> tuple[dict[str, Any], dict[int, int]]:
    prody_logger = logging.getLogger(".prody")
    previous_level = prody_logger.level
    try:
        # ProDy's quiet handler still propagates DEBUG records to parent
        # handlers. Suppress parse chatter at its logger, retaining warnings.
        prody_logger.setLevel(max(prody_logger.getEffectiveLevel(), logging.WARNING))
        protein_dict, _backbone, _other, _icodes, _water = vendor.parse_pdb(
            str(prepared.pdb_path), device=str(vendor.device), parse_all_atoms=True
        )
    except ValueError as exc:
        raise PackingCandidateError(f"cannot parse prepared packing PDB: {exc}") from exc
    except (KeyError, OSError, RuntimeError) as exc:
        raise PackingSystemError(f"cannot parse prepared packing PDB: {exc}") from exc
    finally:
        prody_logger.setLevel(previous_level)
    chain_letters = np.asarray(protein_dict.get("chain_letters")).astype(str)
    positions = np.asarray(protein_dict["R_idx"].detach().cpu().numpy(), dtype=np.int64)
    uid_by_model_index: dict[int, int] = {}
    residues_by_chain = prepared.residues_by_chain
    token_uid_by_position = {
        (str(token.chain_id), int(token.position)): int(token.residue_uid)
        for token in protein_tokens(candidate_plan.candidate.atoms)
    }
    for index, (alias, position) in enumerate(zip(chain_letters, positions, strict=True)):
        source_chain = prepared.chain_by_alias.get(str(alias))
        if source_chain is None:
            raise PackingCandidateError(f"prepared PDB returned unknown chain alias {alias!r}")
        matching = [
            residue
            for residue in residues_by_chain.get(source_chain, ())
            if int(residue.temporary_position) == int(position)
        ]
        if len(matching) != 1:
            raise PackingCandidateError(
                f"prepared PDB residue {alias}:{position} has ambiguous owner mapping"
            )
        token_uid = token_uid_by_position.get(
            (source_chain, int(matching[0].canonical_position))
        )
        if token_uid is None:
            raise PackingCandidateError(
                f"prepared PDB residue {source_chain}:{matching[0].canonical_position} has no source token"
            )
        uid_by_model_index[index] = token_uid

    mutable_mask = np.zeros(len(chain_letters), dtype=np.bool_)
    for index, uid in uid_by_model_index.items():
        mutable_mask[index] = uid in candidate_plan.mutable_residue_uids
    protein_dict["chain_mask"] = torch.as_tensor(
        mutable_mask.astype(np.int32), dtype=torch.int32, device=vendor.device
    )
    try:
        features = vendor.featurize(
            protein_dict,
            cutoff_for_score=8.0,
            use_atom_context=True,
            number_of_ligand_atoms=16,
            model_type="ligand_mpnn",
        )
    except ValueError as exc:
        raise PackingCandidateError(f"cannot featurize packing input: {exc}") from exc
    except (KeyError, OSError, RuntimeError) as exc:
        raise PackingSystemError(f"cannot featurize packing input: {exc}") from exc
    return features, uid_by_model_index


def _run_packer(
    features: dict[str, Any], vendor: _VendorRuntime
) -> tuple[np.ndarray, np.ndarray]:
    try:
        # ``parse_PDB`` uses int32 for the MPNN sequence tensor, while the
        # OpenFold one-hot path inside ``sc_utils`` requires torch.long.
        if "S" in features and features["S"].dtype != torch.long:
            features["S"] = features["S"].long()
        with torch.inference_mode():
            packed = vendor.pack_side_chains(
                features,
                vendor.packer_type,
                vendor.denoising_steps,
                num_samples=vendor.samples,
                repack_everything=False,
                num_context_atoms=16,
            )
    except RuntimeError as exc:
        raise PackingSystemError(f"LigandMPNN side-chain packing failed: {exc}") from exc
    except Exception as exc:
        raise PackingSystemError(f"LigandMPNN side-chain packing failed: {exc}") from exc
    if "X" not in packed or "X_m" not in packed:
        raise PackingSystemError("LigandMPNN packer returned no atom14 coordinates")
    xyz = packed["X"].detach().cpu().numpy()
    mask = packed["X_m"].detach().cpu().numpy()
    if xyz.ndim != 4 or mask.ndim != 3 or xyz.shape[:3] != mask.shape:
        raise PackingSystemError(
            f"unexpected packer output shapes X={xyz.shape}, X_m={mask.shape}"
        )
    if xyz.shape[1] != features["S"].shape[1] or xyz.shape[2] != 14:
        raise PackingSystemError("LigandMPNN atom14 residue count or width changed")
    if (
        xyz.shape[0] != features["S"].shape[0]
        or xyz.shape[3] != 3
        or not np.isfinite(xyz).all()
        or not np.isfinite(mask).all()
    ):
        raise PackingSystemError("LigandMPNN returned invalid atom14 coordinates")
    return np.asarray(xyz, dtype=np.float32), np.asarray(mask, dtype=bool)


def _element_for_atom(atom_name: str) -> str:
    name = atom_name.upper()
    if name.startswith("N"):
        return "N"
    if name.startswith("O"):
        return "O"
    if name.startswith("S"):
        return "S"
    return "C"


def _reconstruct_candidate(
    candidate_plan: _CandidatePlan,
    packed_xyz: np.ndarray,
    packed_mask: np.ndarray,
    uid_by_model_index: Mapping[int, int],
) -> SearchCandidate:
    candidate = candidate_plan.candidate
    source = candidate.atoms
    rows_by_uid = _residue_rows(source)
    model_index_by_uid = {int(uid): int(index) for index, uid in uid_by_model_index.items()}
    max_atom_uid = int(np.asarray(source.atom_uid, dtype=np.int64).max(initial=-1))
    next_atom_uid = max_atom_uid + 1
    fragments: list[Any] = []
    fragment_uids: list[tuple[int, np.ndarray]] = []

    for uid, rows in sorted(rows_by_uid.items(), key=lambda item: int(item[1][0])):
        if uid not in candidate_plan.mutable_residue_uids:
            fragment = source[rows].copy()
            fragments.append(fragment)
            fragment_uids.append((uid, np.asarray(fragment.atom_uid, dtype=np.int64)))
            continue
        target = candidate_plan.target_by_residue_uid[uid]
        model_index = model_index_by_uid.get(uid)
        if model_index is None or model_index >= packed_xyz.shape[0]:
            raise PackingCandidateError(f"packed output has no model residue for UID {uid}")
        source_names = np.asarray(source.atom_name[rows]).astype(str)
        keep_rows = rows[np.isin(source_names, tuple(_BACKBONE))]
        if len(np.flatnonzero(np.asarray(source_names) == "CA")) != 1:
            raise PackingCandidateError(f"mutable residue UID {uid} has no unique CA atom")
        side_names = tuple(name for name in _ATOM14[target] if name not in _BACKBONE)
        atom14_names = _ATOM14[target]
        name_to_slot = {name: slot for slot, name in enumerate(atom14_names)}
        for name in side_names:
            slot = name_to_slot[name]
            if slot >= packed_mask.shape[1] or not bool(packed_mask[model_index, slot]):
                raise PackingSystemError(
                    f"packer returned no coordinate for {target} {uid}:{name}"
                )
        pieces: list[Any] = []
        if len(keep_rows):
            backbone = source[keep_rows].copy()
            backbone.res_name[:] = target
            pieces.append(backbone)
        if side_names:
            template_row = int(keep_rows[np.flatnonzero(np.asarray(source.atom_name[keep_rows]).astype(str) == "CA")[0]])
            side = struc.concatenate(
                [source[np.asarray([template_row], dtype=np.int64)].copy() for _ in side_names]
            )
            side.res_name[:] = target
            side.atom_name[:] = side_names
            side.element[:] = tuple(_element_for_atom(name) for name in side_names)
            side.coord[:] = np.asarray(
                [packed_xyz[model_index, name_to_slot[name]] for name in side_names],
                dtype=np.float32,
            )
            side.coord_valid[:] = True
            # The CA row is only a convenient metadata template.  Atom-level
            # masks must not be copied to every generated side-chain atom;
            # residue-level identity/design/source ownership remains copied.
            for annotation in (
                "centre_atom_mask",
                "motif_coord_condition",
                "token_center_condition",
                "hotspot_condition",
            ):
                if annotation in side.get_annotation_categories():
                    getattr(side, annotation)[:] = False
            side.atom_uid[:] = np.arange(next_atom_uid, next_atom_uid + len(side), dtype=np.int64)
            next_atom_uid += len(side)
            pieces.append(side)
        if not pieces:
            raise PackingCandidateError(f"mutable residue UID {uid} lost its backbone")
        fragment = struc.concatenate(pieces)
        fragments.append(fragment)
        fragment_uids.append((uid, np.asarray(fragment.atom_uid, dtype=np.int64)))

    output = struc.concatenate(fragments)
    output.coord = np.asarray(output.coord, dtype=np.float32)

    # Generate canonical chemistry only inside each changed residue.  Every
    # untouched source bond, including peptide and cyclic closure edges, is
    # carried over by stable AtomUID below; this avoids inventing edges across
    # a source chain gap or context boundary.
    entries: dict[tuple[int, int], int] = {}
    output_rows_by_residue = _residue_rows(output)
    for uid in candidate_plan.mutable_residue_uids:
        rows = output_rows_by_residue.get(uid)
        if rows is None:
            raise PackingCandidateError(f"packed residue UID {uid} is absent from output")
        try:
            local = struc.connect_via_residue_names(
                output[rows], inter_residue=False
            ).as_array()
        except ValueError as exc:
            raise PackingCandidateError(
                f"cannot rebuild {uid} side-chain bonds: {exc}"
            ) from exc
        for raw_i, raw_j, raw_order in np.asarray(local, dtype=np.uint32).reshape((-1, 3)):
            i, j = int(rows[int(raw_i)]), int(rows[int(raw_j)])
            entries[(min(i, j), max(i, j))] = int(raw_order)
    output_row_by_atom_uid = _atom_row_by_uid(output)
    source_uid_by_row = np.asarray(source.residue_uid, dtype=np.int64)
    source_atom_names = np.asarray(source.atom_name).astype(str)
    for raw_i, raw_j, raw_order in _bond_rows_array(source.bonds):
        i, j = int(raw_i), int(raw_j)
        if i >= len(source) or j >= len(source):
            continue
        old_uid_i, old_uid_j = int(source.atom_uid[i]), int(source.atom_uid[j])
        out_i, out_j = output_row_by_atom_uid.get(old_uid_i), output_row_by_atom_uid.get(old_uid_j)
        if out_i is None or out_j is None:
            continue
        residue_i, residue_j = int(source_uid_by_row[i]), int(source_uid_by_row[j])
        if residue_i == residue_j and residue_i in candidate_plan.mutable_residue_uids:
            continue
        if residue_i in candidate_plan.mutable_residue_uids and source_atom_names[i] not in _BACKBONE:
            continue
        if residue_j in candidate_plan.mutable_residue_uids and source_atom_names[j] not in _BACKBONE:
            continue
        key = (min(out_i, out_j), max(out_i, out_j))
        entries[key] = int(raw_order)
    output.bonds = struc.BondList(
        len(output),
        np.asarray([[i, j, order] for (i, j), order in sorted(entries.items())], dtype=np.uint32).reshape((-1, 3)),
    )
    # All topology conditions are source AtomUID keyed.  A mutable residue's
    # side-chain endpoint is protected before packing, so retaining this tuple
    # is safe and keeps explicit cyclic closure semantics unchanged.
    output_uids = set(int(value) for value in np.asarray(output.atom_uid, dtype=np.int64))
    for condition in candidate.topology_conditions:
        if int(condition.atom_uid_a) not in output_uids or int(condition.atom_uid_b) not in output_uids:
            raise PackingCandidateError(
                "packing removed an explicit topology endpoint; residue should have been protected"
            )
    model_parent = dict(candidate.model_parent_residue)
    for uid in candidate_plan.mutable_residue_uids:
        model_parent.pop(uid, None)
    return replace(candidate, atoms=output, model_parent_residue=model_parent)


def _prepare_packing_features(
    candidate_plan: _CandidatePlan,
    *,
    repo_root: Path,
    work_dir: Path,
    vendor: _VendorRuntime,
    pipetools_api: Any,
    model_types: tuple[Any, Any, Any],
) -> tuple[dict[str, Any], dict[int, int]]:
    try:
        work_dir.mkdir(parents=True, exist_ok=False)
    except FileExistsError as exc:
        raise PackingSystemError(f"packing work directory already exists: {work_dir}") from exc
    _candidate_plan, prepared, _unused = _prepare_candidate(
        candidate_plan,
        repo_root=repo_root,
        work_dir=work_dir,
        pipetools_api=pipetools_api,
        model_types=model_types,
    )
    return _feature_dict(candidate_plan, prepared, vendor)


def _feature_batch_key(features: Mapping[str, Any]) -> tuple[Any, ...]:
    """Only concatenate compatible singleton batches; do not pad source tokens."""
    key = []
    for name, value in sorted(features.items()):
        if not isinstance(value, torch.Tensor) or value.ndim == 0 or value.shape[0] != 1:
            raise PackingSystemError(f"packing feature {name!r} is not a singleton tensor batch")
        key.append((name, tuple(value.shape[1:]), value.dtype, value.device))
    return tuple(key)


def _pack_candidate_batch(
    plans: Sequence[tuple[int, _CandidatePlan]],
    *,
    root: Path,
    base_work: Path,
    vendor: _VendorRuntime,
    pipetools_api: Any,
    model_types: tuple[Any, Any, Any],
) -> tuple[dict[str, SearchCandidate], dict[str, str]]:
    # Scope feature tensors (including vendor intermediates) to this one batch.
    prepared: dict[str, SearchCandidate] = {}
    failures: dict[str, str] = {}
    feature_groups: dict[tuple[Any, ...], list[Any]] = {}
    for local_index, candidate_plan in plans:
        candidate = candidate_plan.candidate
        try:
            features, uid_by_model_index = _prepare_packing_features(
                candidate_plan,
                repo_root=root,
                work_dir=base_work / f"{local_index:06d}_{_safe_work_name(candidate.candidate_id)}",
                vendor=vendor,
                pipetools_api=pipetools_api,
                model_types=model_types,
            )
            key = _feature_batch_key(features)
            feature_groups.setdefault(key, []).append(
                (candidate_plan, features, uid_by_model_index)
            )
        except PackingCandidateError as exc:
            failures[candidate.candidate_id] = str(exc)

    for entries in feature_groups.values():
        features = {
            name: torch.cat([entry[1][name] for entry in entries], dim=0)
            for name in entries[0][1]
        }
        xyz, mask = _run_packer(features, vendor)
        for batch_index, (candidate_plan, _features, uid_by_model_index) in enumerate(entries):
            candidate_id = candidate_plan.candidate.candidate_id
            try:
                prepared[candidate_id] = _reconstruct_candidate(
                    candidate_plan, xyz[batch_index], mask[batch_index], uid_by_model_index
                )
            except PackingCandidateError as exc:
                failures[candidate_id] = str(exc)
    return prepared, failures


def pack_mpnn_candidates(
    items: Sequence[tuple[SearchCandidate, SequenceSourcePlan]],
    *,
    reward_config: Mapping[str, Any],
    repo_root: Path,
    work_dir: Path,
    timings: dict[str, float] | None = None,
    antibody_plans: Mapping[str, Any] | None = None,
) -> tuple[dict[str, SearchCandidate], dict[str, str]]:
    """Pack MPNN-generated candidates once, returning successes and failures."""

    normalized = list(items)
    candidate_ids = [candidate.candidate_id for candidate, _plan in normalized]
    if len(candidate_ids) != len(set(candidate_ids)):
        raise PackingSystemError("packing input contains duplicate candidate IDs")
    antibody_plans = {} if antibody_plans is None else dict(antibody_plans)
    unknown_antibody_ids = set(antibody_plans) - set(candidate_ids)
    if unknown_antibody_ids:
        raise PackingSystemError(
            "antibody_plans contains unknown candidate IDs: "
            + ", ".join(sorted(unknown_antibody_ids))
        )
    prepared: dict[str, SearchCandidate] = {}
    failures: dict[str, str] = {}
    mpnn_items: list[tuple[SearchCandidate, SequenceSourcePlan]] = []
    for candidate, plan in normalized:
        if plan.source == "design":
            prepared[candidate.candidate_id] = candidate
        elif plan.source in {"proteinmpnn", "ligandmpnn", "cyclicmpnn"}:
            mpnn_items.append((candidate, plan))
        else:
            raise PackingSystemError(f"unsupported packing sequence source {plan.source!r}")
    if not mpnn_items:
        return prepared, failures

    root = Path(repo_root)
    base_work = Path(work_dir)
    candidate_plans: list[_CandidatePlan] = []
    from .mpnn import (
        MPNNSequenceError,
        _antibody_compatibility_plan,
        _validate_antibody_mpnn_plan,
    )
    for candidate, plan in mpnn_items:
        try:
            antibody_plan = antibody_plans.get(candidate.candidate_id)
            explicit_mutable: frozenset[int] | None = None
            if antibody_plan is not None:
                selection = _validate_antibody_mpnn_plan(
                    candidate, antibody_plan, sequence_plan=plan
                )
                explicit_mutable = selection.plan.mutable_uid_set
                if not explicit_mutable:
                    prepared[candidate.candidate_id] = candidate
                    continue
            packing_plan = (
                _antibody_compatibility_plan(plan, selection)
                if antibody_plan is not None
                else plan
            )
            candidate_plan = _candidate_plan(
                candidate,
                packing_plan,
                mutable_residue_uids=explicit_mutable,
                design_chain_ids=(
                    frozenset(selection.plan.design_chain_ids)
                    if antibody_plan is not None
                    else None
                ),
            )
        except (PackingCandidateError, MPNNSequenceError) as exc:
            failures[candidate.candidate_id] = str(exc)
            continue
        if not candidate_plan.mutable_residue_uids:
            # Motif-only/fixed-context plans need no model invocation and are
            # returned bit-for-bit unchanged.
            prepared[candidate.candidate_id] = candidate
            continue
        candidate_plans.append(candidate_plan)
    if not candidate_plans:
        return prepared, failures
    try:
        runtime_started = time.perf_counter()
        vendor = _load_vendor_runtime(root, reward_config)
        from .mpnn import _load_pipetools

        pipetools_api, _sequence_config, model_types, _runtime_paths, _source = _load_pipetools(root)
        if timings is not None:
            timings["runtime_load_seconds"] = time.perf_counter() - runtime_started
    except PackingSystemError:
        raise
    except Exception as exc:
        raise PackingSystemError(f"cannot initialize MPNN packing protocol: {exc}") from exc

    # Group across tasks by protein length so the normal AME candidates can
    # share a full batch. Stage at most 64 candidates' features on the device;
    # exact tensor signatures below handle any remaining context differences.
    plans_by_length: dict[int, list[tuple[int, _CandidatePlan]]] = {}
    for local_index, candidate_plan in enumerate(candidate_plans):
        length = len(protein_tokens(candidate_plan.candidate.atoms))
        plans_by_length.setdefault(length, []).append((local_index, candidate_plan))
    for length_plans in plans_by_length.values():
        for offset in range(0, len(length_plans), _PACKING_BATCH_SIZE):
            batch_started = time.perf_counter()
            batch_prepared, batch_failures = _pack_candidate_batch(
                length_plans[offset:offset + _PACKING_BATCH_SIZE],
                root=root,
                base_work=base_work,
                vendor=vendor,
                pipetools_api=pipetools_api,
                model_types=model_types,
            )
            prepared.update(batch_prepared)
            failures.update(batch_failures)
            if timings is not None:
                timings["batch_work_seconds"] = timings.get("batch_work_seconds", 0.0) + (time.perf_counter() - batch_started)
    return prepared, failures


