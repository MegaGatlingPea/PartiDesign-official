"""Bounded LigandMPNN side-chain packing for deferred PartiScore rewards.

The sequence stage and this adapter intentionally have separate ownership.  A
``SequenceSourcePlan`` describes the sequence already generated by MPNN; this
module only replaces mutable standard-protein side chains in that candidate.
The candidate's backbone, fixed context, source annotations and explicit
topology remain authoritative.
"""

